"""Write beats.json and beats.md: every narration part with its cue time in the FINAL video.

Run after any change to holds.json:   python export_beats.py
Times follow holds.json, so the map is always in step with the cut that build_long.py renders.
"""
import os, sys, json, re
KIT = os.path.dirname(os.path.abspath(__file__))
if KIT not in sys.path: sys.path.insert(0, KIT)
os.environ.setdefault("SS", "1")
import build_long as B, narration, beats_def

def seg_table():
    out, acc = {}, 0.0
    for kind, k, T in B.SEGS:
        key = (kind, B.names[k]) if kind == "story" else (kind, k)
        out[key] = (acc, k); acc += round(T * B.FPS) / B.FPS
    return out, acc

def main():
    segs, total = seg_table()
    script = {name: (s, e, txt) for s, e, name, txt in narration.N}
    slides, problems = [], []
    for name, (kind, key), parts in beats_def.SLIDES:
        s0, e0, txt = script[name]
        joined = " ".join(p[0] for p in parts)
        if joined != txt:
            problems.append(f"{name}: beat-map parts do not match narration.py text")
        seg0, k = segs[(kind, key)]
        hs = B.holds_for(kind, k)
        scale = B.K if kind == "story" else 1.0
        rows = []
        for i, (ptxt, cue, shows) in enumerate(parts, 1):
            t = round(seg0 + B.held_time(cue * scale, hs), 2)
            shows = re.sub(r"\{([\d.]+)\}", lambda m: f"{seg0 + B.held_time(float(m.group(1)) * scale, hs):.1f} s", shows)
            rows.append({"part": f"P{i}", "text": ptxt, "words": len(ptxt.split()), "cue": t, "shows": shows})
        w = sum(r["words"] for r in rows)
        slides.append({"slide": name, "start": s0, "end": e0, "length": round(e0 - s0, 1), "words": w,
                       "words_per_second": round(w / (e0 - s0), 2), "parts": rows})
    silent = [{"slide": n, "start": s, "end": e} for s, e, n, t in narration.N if not t]
    data = {"video_length": round(total, 2), "holds_file": "holds.json", "slides": slides, "silent_slides": silent,
            "rules": {"earliest_start_before_cue": 0.3, "latest_start_after_cue": 1.5, "voice_led_cue_after_part_end": 0.2, "slide_lead_in": 0.15, "slide_tail": 0.3, "min_gap_between_parts": 0.25,
                      "max_words_per_second": 2.5}}
    json.dump(data, open(os.path.join(KIT, "beats.json"), "w"), indent=1, ensure_ascii=False)
    with open(os.path.join(KIT, "beats.md"), "w") as f:
        f.write(f"# Beat map (video length {total:.1f} s)\n\nGenerated by export_beats.py from beats_def.py and holds.json. Times are seconds in the final video.\n\n")
        for sl in slides:
            f.write(f"## {sl['slide']}  ({sl['start']:.1f} to {sl['end']:.1f} s, {sl['words']} words, {sl['words_per_second']} words/s)\n\n| Part | Cue (s) | On screen at the cue | Text |\n|---|---|---|---|\n")
            for r in sl["parts"]:
                f.write(f"| {r['part']} | {r['cue']:.1f} | {r['shows']} | {r['text']} |\n")
            f.write("\n")
        f.write("## Silent slides\n\n" + "".join(f"- {s['slide']}: {s['start']:.1f} to {s['end']:.1f} s\n" for s in silent))
    print(f"beats.json and beats.md written; video {total:.1f} s; {sum(len(s['parts']) for s in slides)} parts")
    for p in problems: print("PROBLEM:", p)
    return 1 if problems else 0

if __name__ == "__main__":
    sys.exit(main())
